const fs = require('fs');
const path = require('path');
const assert = require('node:assert/strict');
const {chromium} = require(path.resolve('.test-artifacts/node_modules/playwright'));
const base = process.env.TCC_AUTH_BASE;
const user = process.env.TCC_AUTH_TEST_USER;
const email = user+'@example.test';
const password = 'Teste-Conta!8867';
const newPassword = 'Senha-Nova!9638';
const outbox = path.resolve('.test-artifacts/auth-mailbox.json');
const screenshots = path.resolve('docs/auth-evidencias');
const mail = needle => {
    const messages = JSON.parse(fs.readFileSync(outbox,'utf8'));
    return messages.filter(m=>m.subject.includes(needle)&&m.to===email).at(-1);
};
(async()=>{
 const browser = await chromium.launch({executablePath:'C:/Program Files/Google/Chrome/Application/chrome.exe',headless:true});
 try {
  const page = await browser.newPage({viewport:{width:1440,height:1000}});
  const errors=[];page.on('pageerror',e=>errors.push(e.message));
  await page.goto(base+'/login/');
  await page.screenshot({path:path.join(screenshots,'login-desktop.png'),fullPage:true});
  await page.setViewportSize({width:390,height:844});
  await page.screenshot({path:path.join(screenshots,'login-mobile.png'),fullPage:true});
  assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth));
  await page.fill('#password','exemplo');
  await page.getByRole('button',{name:'Mostrar senha',exact:true}).click();
  assert.equal(await page.locator('#password').getAttribute('type'),'text');
  console.log('PASS login desktop/mobile, sem rolagem horizontal, mostrar/ocultar senha');
  await page.setViewportSize({width:1440,height:1100});
  await page.goto(base+'/login/cadastro/');
  await page.screenshot({path:path.join(screenshots,'cadastro-desktop.png'),fullPage:true});
  await page.fill('#id_first_name','Ana');await page.fill('#id_username',user);await page.fill('#id_email',email);
  await page.fill('#id_password1',password);await page.fill('#id_password2',password);
  await page.getByRole('button',{name:'Criar minha conta'}).click();
  await page.waitForURL(base+'/login/cadastro/enviado/');
  const activation=mail('Confirme seu email');
  assert.ok(activation && activation.html && activation.text);
  assert.ok(!activation.text.includes(password));
  const activationUrl=activation.text.match(/http:\/\/[^\s]+\/confirmar-email\/[^\s]+/)[0];
  await page.goto(base+'/login/');await page.fill('#username',user);await page.fill('#password',password);
  await page.getByRole('button',{name:/^Entrar/}).click();await page.waitForSelector('.form-alert');
  assert.equal(new URL(page.url()).pathname,'/login/');
  await page.goto(activationUrl);await page.getByRole('button',{name:'Confirmar meu email'}).click();
  await page.waitForURL(base+'/login/confirmado/');
  assert.ok(mail('Sua conta está pronta'));
  console.log('PASS cadastro, SMTP multipart real local, bloqueio antes de confirmação, ativação e boas-vindas');
  await page.goto(base+'/login/recuperar-senha/');
  await page.screenshot({path:path.join(screenshots,'recuperacao-desktop.png'),fullPage:true});
  await page.fill('#id_email',email);await page.getByRole('button',{name:'Enviar link de recuperação'}).click();
  await page.waitForURL(base+'/login/recuperar-senha/enviado/');
  const reset=mail('Redefina sua senha');assert.ok(reset.html && reset.text);
  const resetUrl=reset.text.match(/http:\/\/[^\s]+\/redefinir-senha\/[^\s]+/)[0];
  await page.goto(resetUrl);
  await page.waitForSelector('#id_new_password1');
  await page.fill('#id_new_password1',newPassword);await page.fill('#id_new_password2',newPassword);
  await page.getByRole('button',{name:'Salvar nova senha'}).click();await page.waitForURL(base+'/login/senha-redefinida/');
  await page.goto(resetUrl);
  assert.ok((await page.locator('main').textContent()).includes('já foi usado'));
  await page.goto(base+'/login/');await page.fill('#username',user);await page.fill('#password',password);
  await page.getByRole('button',{name:/^Entrar/}).click();await page.waitForSelector('.form-alert');
  await page.fill('#password',newPassword);await page.getByRole('button',{name:/^Entrar/}).click();await page.waitForURL(base+'/');
  console.log('PASS recuperação via SMTP local, nova senha, senha antiga rejeitada, token usado rejeitado, login');
  assert.deepEqual(errors,[]);
  console.log('PASS nenhuma exceção JavaScript não tratada; nenhum email externo enviado');
 } finally {await browser.close();}
})().catch(e=>{console.error(e);process.exitCode=1;});
